const BACKUPS_DIR = path.join(__dirname, '..', 'backups');

// Ensure backups directory exists
const ensureBackupDir = () => {
  if (!fs.existsSync(BACKUPS_DIR)) {
    fs.mkdirSync(BACKUPS_DIR, { recursive: true });
  }
  return BACKUPS_DIR;
};

// Ensure system_backups table exists in database
let tableSynced = false;
const ensureBackupTable = async () => {
  if (tableSynced) return;
  try {
    await SystemBackup.sync({ alter: true });
    tableSynced = true;
  } catch (err) {
    try {
      await sequelize.query(`
        CREATE TABLE IF NOT EXISTS system_backups (
          id SERIAL PRIMARY KEY,
          filename VARCHAR(255) NOT NULL,
          filepath VARCHAR(500) NOT NULL,
          format VARCHAR(20) NOT NULL DEFAULT 'json',
          file_size BIGINT NOT NULL DEFAULT 0,
          total_records INTEGER NOT NULL DEFAULT 0,
          table_counts JSONB,
          status VARCHAR(30) NOT NULL DEFAULT 'completed',
          error_message TEXT,
          notes TEXT,
          created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
          created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
        );
      `);
      tableSynced = true;
    } catch (rawErr) {
      console.warn('ensureBackupTable warning:', rawErr.message);
    }
  }
};

